import SwiftSyntax

struct ConstructorEmitter {
  private static let inaccessibleKeywordCases: Set<String> = [
    "_consuming", "_mutating", "dependsOn", "modify", "read", "scoped",
  ]

  private var bindings: [String] = []
  private var nextBindingID = 0

  mutating func render(root: ParsedExpectedSyntax, factoryName: String) throws -> String {
    let returnType: String
    let returnExpression: String

    switch root {
    case .sourceFile(let file):
      returnType = "SwiftSyntax.SourceFileSyntax"
      returnExpression = try emit(file)
    case .declaration(let declaration):
      returnType = "SwiftSyntax.DeclSyntax"
      returnExpression = try emit(declaration)
    case .expression(let expression):
      returnType = "SwiftSyntax.ExprSyntax"
      returnExpression = try emit(expression)
    case .declarations(let declarations):
      returnType = "[SwiftSyntax.DeclSyntax]"
      let elements = try declarations.map { try emit($0) }
      returnExpression = arrayExpression(elements)
    }

    let body = bindings.map { indent($0, spaces: 2) }.joined(separator: "\n")
    let separatedBody = body.isEmpty ? "" : "\(body)\n"
    return """
      // Generated by ExpectedSyntaxGen. Do not edit by hand.
      // Regenerate with the same SwiftSyntax version used by the consumer.
      import SwiftSyntax

      public func \(factoryName)() -> \(returnType) {
      \(separatedBody)  return \(returnExpression)
      }

      """
  }

  private mutating func emit<Node: SyntaxProtocol>(_ node: Node) throws -> String {
    if ObjectIdentifier(Node.self) != ObjectIdentifier(node.syntaxNodeType) {
      guard let concrete = node.syntaxNodeType.init(node) else {
        throw ExpectedSyntaxGenerationError.unsupportedMetadata(
          "could not recover the concrete child of \(swiftTypeName(Node.self))"
        )
      }
      let childBinding = try emit(concrete)
      return appendBinding(
        type: swiftTypeName(Node.self),
        expression: "\(swiftTypeName(Node.self))(\(childBinding))"
      )
    }

    if let token = TokenSyntax(node) {
      return try emitToken(token)
    }

    switch Node.structure {
    case .layout:
      return try emitLayout(node)
    case .collection(let elementType):
      return try emitCollection(node, elementType: elementType)
    case .choices:
      throw ExpectedSyntaxGenerationError.unsupportedMetadata(
        "\(swiftTypeName(Node.self)) did not expose its concrete child"
      )
    @unknown default:
      throw ExpectedSyntaxGenerationError.unsupportedMetadata(
        "\(swiftTypeName(Node.self)) uses an unknown SwiftSyntax node structure"
      )
    }
  }

  private mutating func emitLayout<Node: SyntaxProtocol>(_ node: Node) throws -> String {
    let children = try SyntaxMetadataAdapter.layoutChildren(of: node)
    let arguments = try children.map { child in
      let expression: String
      if let value = child.value {
        expression = try emit(value)
      } else if let optionalValueType = child.optionalValueType {
        expression = "\(swiftTypeName(optionalValueType))?.none"
      } else {
        throw ExpectedSyntaxGenerationError.unsupportedMetadata(
          "an absent layout child was not described as optional"
        )
      }
      if let label = child.initializerLabel {
        return "\(label): \(expression)"
      }
      return expression
    }

    return appendBinding(
      type: swiftTypeName(Node.self),
      expression: callExpression(type: swiftTypeName(Node.self), arguments: arguments)
    )
  }

  private mutating func emitCollection<Node: SyntaxProtocol>(
    _ node: Node,
    elementType: SyntaxProtocol.Type
  ) throws -> String {
    var elements: [String] = []
    elements.reserveCapacity(node.children(viewMode: .all).count)
    for child in node.children(viewMode: .all) {
      guard let element = elementType.init(child) else {
        throw ExpectedSyntaxGenerationError.unsupportedMetadata(
          "a child of \(swiftTypeName(Node.self)) cannot be represented as \(swiftTypeName(elementType))"
        )
      }
      elements.append(try emit(element))
    }

    return appendBinding(
      type: swiftTypeName(Node.self),
      expression: "\(swiftTypeName(Node.self))(\(arrayExpression(elements)))"
    )
  }

  private mutating func emitToken(_ token: TokenSyntax) throws -> String {
    let kind = try tokenKindExpression(token)
    let arguments = [
      kind,
      "leadingTrivia: \(triviaExpression(token.leadingTrivia))",
      "trailingTrivia: \(triviaExpression(token.trailingTrivia))",
      "presence: \(token.presence == .present ? ".present" : ".missing")",
    ]
    return appendBinding(
      type: "SwiftSyntax.TokenSyntax",
      expression: callExpression(type: "SwiftSyntax.TokenSyntax", arguments: arguments)
    )
  }

  private func tokenKindExpression(_ token: TokenSyntax) throws -> String {
    if let associated = try associatedTokenKindExpression(token.tokenKind) {
      return associated
    }
    return try fixedTokenKindExpression(token)
  }

  private func associatedTokenKindExpression(_ kind: TokenKind) throws -> String? {
    switch kind {
    case .binaryOperator(let text):
      return ".binaryOperator(\(SwiftStringLiteralEncoder.encode(text)))"
    case .dollarIdentifier(let text):
      return ".dollarIdentifier(\(SwiftStringLiteralEncoder.encode(text)))"
    case .floatLiteral(let text): return ".floatLiteral(\(SwiftStringLiteralEncoder.encode(text)))"
    case .identifier(let text): return ".identifier(\(SwiftStringLiteralEncoder.encode(text)))"
    case .integerLiteral(let text):
      return ".integerLiteral(\(SwiftStringLiteralEncoder.encode(text)))"
    case .keyword(let keyword):
      let name = String(describing: keyword)
      guard !Self.inaccessibleKeywordCases.contains(name) else {
        throw ExpectedSyntaxGenerationError.unsupportedMetadata(
          "keyword '\(name)' is SPI in this SwiftSyntax release and has no public TokenKind constructor"
        )
      }
      return ".keyword(.`\(name)`)"
    case .postfixOperator(let text):
      return ".postfixOperator(\(SwiftStringLiteralEncoder.encode(text)))"
    case .prefixOperator(let text):
      return ".prefixOperator(\(SwiftStringLiteralEncoder.encode(text)))"
    case .rawStringPoundDelimiter(let text):
      return ".rawStringPoundDelimiter(\(SwiftStringLiteralEncoder.encode(text)))"
    case .regexLiteralPattern(let text):
      return ".regexLiteralPattern(\(SwiftStringLiteralEncoder.encode(text)))"
    case .regexPoundDelimiter(let text):
      return ".regexPoundDelimiter(\(SwiftStringLiteralEncoder.encode(text)))"
    case .shebang(let text): return ".shebang(\(SwiftStringLiteralEncoder.encode(text)))"
    case .stringSegment(let text):
      return ".stringSegment(\(SwiftStringLiteralEncoder.encode(text)))"
    case .unknown(let text): return ".unknown(\(SwiftStringLiteralEncoder.encode(text)))"
    default: return nil
    }
  }

  private func fixedTokenKindExpression(_ token: TokenSyntax) throws -> String {
    switch token.tokenKind {
    case .arrow: return ".arrow"
    case .atSign: return ".atSign"
    case .backslash: return ".backslash"
    case .backtick: return ".backtick"
    case .colon: return ".colon"
    case .comma: return ".comma"
    case .ellipsis: return ".ellipsis"
    case .endOfFile: return ".endOfFile"
    case .equal: return ".equal"
    case .exclamationMark: return ".exclamationMark"
    case .infixQuestionMark: return ".infixQuestionMark"
    case .leftAngle: return ".leftAngle"
    case .leftBrace: return ".leftBrace"
    case .leftParen: return ".leftParen"
    case .leftSquare: return ".leftSquare"
    case .multilineStringQuote: return ".multilineStringQuote"
    case .period: return ".period"
    case .postfixQuestionMark: return ".postfixQuestionMark"
    case .pound: return ".pound"
    case .poundAvailable: return ".poundAvailable"
    case .poundElse: return ".poundElse"
    case .poundElseif: return ".poundElseif"
    case .poundEndif: return ".poundEndif"
    case .poundIf: return ".poundIf"
    case .poundSourceLocation: return ".poundSourceLocation"
    case .poundUnavailable: return ".poundUnavailable"
    case .prefixAmpersand: return ".prefixAmpersand"
    case .regexSlash: return ".regexSlash"
    case .rightAngle: return ".rightAngle"
    case .rightBrace: return ".rightBrace"
    case .rightParen: return ".rightParen"
    case .rightSquare: return ".rightSquare"
    case .semicolon: return ".semicolon"
    case .singleQuote: return ".singleQuote"
    case .stringQuote: return ".stringQuote"
    case .wildcard: return ".wildcard"
    default:
      if token.text == "::" {
        return ".colonColon"
      }
      throw ExpectedSyntaxGenerationError.unsupportedMetadata(
        "the token \(SwiftStringLiteralEncoder.encode(token.text)) uses a TokenKind "
          + "that this generator does not support"
      )
    }
  }

  private func triviaExpression(_ trivia: Trivia) -> String {
    let pieces = trivia.map(triviaPieceExpression)
    return "SwiftSyntax.Trivia(pieces: \(arrayExpression(pieces)))"
  }

  private func triviaPieceExpression(_ piece: TriviaPiece) -> String {
    switch piece {
    case .backslashes(let count): return ".backslashes(\(count))"
    case .blockComment(let text): return ".blockComment(\(SwiftStringLiteralEncoder.encode(text)))"
    case .carriageReturns(let count): return ".carriageReturns(\(count))"
    case .carriageReturnLineFeeds(let count): return ".carriageReturnLineFeeds(\(count))"
    case .docBlockComment(let text):
      return ".docBlockComment(\(SwiftStringLiteralEncoder.encode(text)))"
    case .docLineComment(let text):
      return ".docLineComment(\(SwiftStringLiteralEncoder.encode(text)))"
    case .formfeeds(let count): return ".formfeeds(\(count))"
    case .lineComment(let text): return ".lineComment(\(SwiftStringLiteralEncoder.encode(text)))"
    case .newlines(let count): return ".newlines(\(count))"
    case .pounds(let count): return ".pounds(\(count))"
    case .spaces(let count): return ".spaces(\(count))"
    case .tabs(let count): return ".tabs(\(count))"
    case .unexpectedText(let text):
      return ".unexpectedText(\(SwiftStringLiteralEncoder.encode(text)))"
    case .verticalTabs(let count): return ".verticalTabs(\(count))"
    }
  }

  private mutating func appendBinding(type: String, expression: String) -> String {
    let name = "node\(nextBindingID)"
    nextBindingID += 1
    bindings.append("let \(name): \(type) = \(expression)")
    return name
  }

  private func callExpression(type: String, arguments: [String]) -> String {
    guard !arguments.isEmpty else { return "\(type)()" }
    let body = arguments.map { "\(indent($0, spaces: 2))," }.joined(separator: "\n")
    return "\(type)(\n\(body)\n)"
  }

  private func arrayExpression(_ elements: [String]) -> String {
    guard !elements.isEmpty else { return "[]" }
    let body = elements.map { "\(indent($0, spaces: 2))," }.joined(separator: "\n")
    return "[\n\(body)\n]"
  }

  private func indent(_ value: String, spaces: Int) -> String {
    let prefix = String(repeating: " ", count: spaces)
    return value.split(separator: "\n", omittingEmptySubsequences: false)
      .map { "\(prefix)\($0)" }
      .joined(separator: "\n")
  }
}
